-- ---------- Catálogo (1 linha por produto) ----------
create table if not exists public.catalog (
  id          text primary key check (char_length(id) between 1 and 80),
  cat         text not null check (cat in ('shishas','essencias','carvao','acessorios','packs')),
  pos         integer not null default 0,
  data        jsonb not null,
  updated_at  timestamptz not null default now()
);

-- ---------- Dados da loja (1 única linha) ----------
create table if not exists public.settings (
  id          integer primary key default 1 check (id = 1),
  store       jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

-- ---------- Encomendas ----------
create table if not exists public.orders (
  n           bigint generated by default as identity (start with 1001) primary key,
  created_at  timestamptz not null default now(),
  items       jsonb not null,
  total       numeric(10,2) not null,
  estado      text not null default 'nova' check (estado in ('nova','confirmada','pronta','entregue','cancelada')),
  canal       text not null default 'WhatsApp',
  exemplo     boolean not null default false
);

-- ---------- Segurança: Row Level Security ----------
alter table public.catalog  enable row level security;
alter table public.settings enable row level security;
alter table public.orders   enable row level security;

-- Catálogo e dados da loja: todos podem LER; só o dono (com login) pode alterar
drop policy if exists "catalog_read"  on public.catalog;
drop policy if exists "catalog_write" on public.catalog;
create policy "catalog_read"  on public.catalog  for select using (true);
create policy "catalog_write" on public.catalog  for all to authenticated using (true) with check (true);

drop policy if exists "settings_read"  on public.settings;
drop policy if exists "settings_write" on public.settings;
create policy "settings_read"  on public.settings for select using (true);
create policy "settings_write" on public.settings for all to authenticated using (true) with check (true);

-- Encomendas: os clientes só podem CRIAR (com limites); só o dono vê, altera e apaga
drop policy if exists "orders_insert_public" on public.orders;
drop policy if exists "orders_owner"         on public.orders;
create policy "orders_insert_public" on public.orders for insert to anon, authenticated
  with check (
    estado = 'nova'
    and exemplo = false
    and jsonb_typeof(items) = 'array'
    and jsonb_array_length(items) between 1 and 30
    and total >= 0 and total <= 5000
    and octet_length(items::text) < 8000
  );
create policy "orders_owner" on public.orders for all to authenticated using (true) with check (true);

-- ---------- Fotos dos produtos (Storage) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('produtos', 'produtos', true, 2097152, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 2097152,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "fotos_read"   on storage.objects;
drop policy if exists "fotos_write"  on storage.objects;
drop policy if exists "fotos_update" on storage.objects;
drop policy if exists "fotos_delete" on storage.objects;
create policy "fotos_read"   on storage.objects for select using (bucket_id = 'produtos');
create policy "fotos_write"  on storage.objects for insert to authenticated with check (bucket_id = 'produtos');
create policy "fotos_update" on storage.objects for update to authenticated using (bucket_id = 'produtos');
create policy "fotos_delete" on storage.objects for delete to authenticated using (bucket_id = 'produtos');
